// ─────────────────────────────────────────────────────────────
// Helper: generate QR code as data URL
// ─────────────────────────────────────────────────────────────
export async function generateQR(text: string): Promise<string> {
  try {
    return await QRCode.toDataURL(text, {
      width: 120,
      margin: 1,
      color: { dark: "#15857A", light: "#FFFFFF" },
    });
  } catch {
    return "";
  }
}

// ─────────────────────────────────────────────────────────────
// Helper: amount to words (Indian/Pakistani numbering)
// ─────────────────────────────────────────────────────────────
function numberToWords(num: number): string {
  if (num === 0) return "Zero";
  const ones = ["", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"];
  const teens = ["Ten", "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen", "Sixteen", "Seventeen", "Eighteen", "Nineteen"];
  const tens = ["", "", "Twenty", "Thirty", "Forty", "Fifty", "Sixty", "Seventy", "Eighty", "Ninety"];
  function twoDigits(n: number): string {
    if (n < 10) return ones[n];
    if (n < 20) return teens[n - 10];
    return tens[Math.floor(n / 10)] + (n % 10 ? " " + ones[n % 10] : "");
  }
  function threeDigits(n: number): string {
    const h = Math.floor(n / 100);
    const r = n % 100;
    let s = "";
    if (h > 0) s += ones[h] + " Hundred";
    if (r > 0) s += (h > 0 ? " " : "") + twoDigits(r);
    return s;
  }
  const thousands = Math.floor(num / 1000);
  const remainder = num % 1000;
  let result = "";
  if (thousands > 0) result += twoDigits(thousands) + " Thousand";
  if (remainder > 0) result += (thousands > 0 ? " " : "") + threeDigits(remainder);
  return result.trim();
}

// ─────────────────────────────────────────────────────────────
// Helper: draw school letterhead on PDF
// ─────────────────────────────────────────────────────────────
function drawLetterhead(doc: jsPDF, school: SchoolInfo, options?: { compact?: boolean }) {
  const compact = options?.compact;
  const margin = 14;
  const pageWidth = doc.internal.pageSize.getWidth();

  // Top accent bar
  doc.setFillColor(21, 133, 122); // primary teal
  doc.rect(0, 0, pageWidth, 4, "F");

  // Logo
  let logoX = margin;
  let logoSize = compact ? 14 : 18;
  if (school.logo) {
    try {
      const format = school.logo.includes("image/png") ? "PNG" : "JPEG";
      doc.addImage(school.logo, format, margin, compact ? 8 : 10, logoSize, logoSize);
    } catch {
      // If logo fails, draw placeholder
      doc.setFillColor(21, 133, 122);
      doc.roundedRect(margin, compact ? 8 : 10, logoSize, logoSize, 2, 2, "F");
    }
  } else {
    doc.setFillColor(21, 133, 122);
    doc.roundedRect(margin, compact ? 8 : 10, logoSize, logoSize, 2, 2, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(compact ? 8 : 10);
    doc.setFont("helvetica", "bold");
    doc.text("SMS", margin + logoSize / 2, compact ? 8 + logoSize / 2 + 1 : 10 + logoSize / 2 + 1, { align: "center" });
  }

  // School name + address
  doc.setTextColor(21, 133, 122);
  doc.setFontSize(compact ? 13 : 16);
  doc.setFont("helvetica", "bold");
  doc.text(school.name, margin + logoSize + 4, compact ? 15 : 19);

  doc.setTextColor(80, 80, 80);
  doc.setFontSize(compact ? 7 : 8);
  doc.setFont("helvetica", "normal");
  doc.text(school.address, margin + logoSize + 4, compact ? 20 : 24);
  doc.text(`Phone: ${school.phone}  •  Email: ${school.email}`, margin + logoSize + 4, compact ? 24 : 28);

  // Horizontal divider
  doc.setDrawColor(21, 133, 122);
  doc.setLineWidth(0.5);
  doc.line(margin, compact ? 28 : 34, pageWidth - margin, compact ? 28 : 34);
}

// ─────────────────────────────────────────────────────────────
// Helper: draw footer on PDF
// ─────────────────────────────────────────────────────────────
function drawFooter(doc: jsPDF, school: SchoolInfo) {
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;

  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.3);
  doc.line(margin, pageHeight - 20, pageWidth - margin, pageHeight - 20);

  doc.setFontSize(7);
  doc.setTextColor(150, 150, 150);
  doc.setFont("helvetica", "italic");
  doc.text(
    `Generated by EduDesk SMS on ${new Date().toLocaleString("en-GB")}`,
    margin,
    pageHeight - 14
  );
  doc.text(
    `${school.name} • Session ${school.session}`,
    pageWidth - margin,
    pageHeight - 14,
    { align: "right" }
  );
}

// ─────────────────────────────────────────────────────────────
// Helper: open PDF in new tab for print
// ─────────────────────────────────────────────────────────────
function openPDF(doc: jsPDF, filename: string) {
  const blobUrl = doc.output("bloburl");
  // Open in new tab
  if (typeof window !== "undefined") {
    window.open(blobUrl, "_blank");
  }
  return blobUrl;
}

// ─────────────────────────────────────────────────────────────
// 1. FEE RECEIPT (A5 size — 148 × 210 mm)
// ─────────────────────────────────────────────────────────────
export async function printFeeReceipt(
  collection: FeeCollection,
  student: Student | undefined,
  school: SchoolInfo
) {
  const doc = new jsPDF({ unit: "mm", format: "a5" });
  const pageWidth = doc.internal.pageSize.getWidth(); // 148
  const margin = 10;

  // Compact letterhead
  drawLetterhead(doc, school, { compact: true });

  let y = 34;
  // Title
  doc.setTextColor(20, 20, 20);
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.text("FEE RECEIPT", pageWidth / 2, y, { align: "center" });
  y += 6;

  // Receipt meta
  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(80, 80, 80);
  doc.text(`Receipt No: ${collection.receiptNo}`, margin, y);
  doc.text(`Date: ${new Date(collection.date).toLocaleDateString("en-GB")}`, pageWidth - margin, y, { align: "right" });
  y += 4;
  doc.setDrawColor(220, 220, 220);
  doc.line(margin, y, pageWidth - margin, y);
  y += 5;

  // Student info
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(20, 20, 20);
  doc.text("Student Details", margin, y);
  y += 4;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(60, 60, 60);
  if (student) {
    doc.text(`Name: ${student.name}`, margin, y);
    doc.text(`Class: ${student.class}-${student.section}`, pageWidth - margin, y, { align: "right" });
    y += 4;
    doc.text(`ID: ${student.id}`, margin, y);
    doc.text(`Roll No: ${student.rollNo}`, pageWidth - margin, y, { align: "right" });
    y += 4;
    doc.text(`Father: ${student.fatherName}`, margin, y);
    doc.text(`Phone: ${student.fatherPhone}`, pageWidth - margin, y, { align: "right" });
    y += 4;
    if (student.isHosteller) {
      doc.setTextColor(255, 106, 59);
      doc.setFont("helvetica", "bold");
      doc.text("HOSTELLER", margin, y);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(60, 60, 60);
      y += 4;
    }
  }
  y += 3;

  // Fee breakdown table
  const rows: (string | number)[][] = [];
  if (collection.tuition) rows.push(["Tuition Fee", `Rs. ${collection.tuition.toLocaleString()}`]);
  if (collection.admission) rows.push(["Admission Fee", `Rs. ${collection.admission.toLocaleString()}`]);
  if (collection.hostel) rows.push(["Hostel Fee", `Rs. ${collection.hostel.toLocaleString()}`]);
  if (rows.length === 0) rows.push([collection.feeType || "Fee", `Rs. ${collection.amount.toLocaleString()}`]);

  autoTable(doc, {
    startY: y,
    head: [["Fee Type", "Amount"]],
    body: rows,
    theme: "striped",
    headStyles: { fillColor: [21, 133, 122], textColor: 255, fontSize: 9, fontStyle: "bold" },
    bodyStyles: { fontSize: 9, textColor: [40, 40, 40] },
    alternateRowStyles: { fillColor: [244, 241, 233] },
    margin: { left: margin, right: margin },
    styles: { cellPadding: 2.5 },
  });

  // @ts-ignore — autoTable extends doc with lastAutoTable
  y = (doc as any).lastAutoTable.finalY + 4;

  // Total
  doc.setFillColor(21, 133, 122);
  doc.rect(margin, y, pageWidth - 2 * margin, 8, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.text("TOTAL", margin + 2, y + 5.5);
  doc.text(`Rs. ${collection.amount.toLocaleString()}`, pageWidth - margin - 2, y + 5.5, { align: "right" });
  y += 12;

  // Payment mode + amount in words
  doc.setTextColor(60, 60, 60);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.text(`Payment Mode: ${collection.mode}`, margin, y);
  y += 4;
  doc.text(`Amount in words: ${numberToWords(collection.amount)} Rupees only`, margin, y);
  y += 6;

  // QR code on right, signature on left
  const qrData = await generateQR(`${collection.receiptNo}|${student?.id || ""}|${collection.amount}`);
  if (qrData) {
    try {
      doc.addImage(qrData, "PNG", pageWidth - 28, y, 18, 18);
    } catch {}
  }

  // Signature line
  doc.setDrawColor(120, 120, 120);
  doc.setLineWidth(0.3);
  doc.line(margin, y + 14, margin + 35, y + 14);
  doc.setFontSize(7);
  doc.setTextColor(100, 100, 100);
  doc.text("Received by (Accountant)", margin, y + 18);
  doc.text("Scan to verify", pageWidth - 19, y + 19, { align: "center" });

  drawFooter(doc, school);

  openPDF(doc, `receipt-${collection.receiptNo}.pdf`);
  return doc;
}

