  doc.rect(photoX, photoY, 20, 24, "F");
  doc.setDrawColor(180, 180, 180);
  doc.rect(photoX, photoY, 20, 24, "S");
  doc.setTextColor(150, 150, 150);
  doc.setFontSize(6);
  doc.text("PHOTO", photoX + 10, photoY + 13, { align: "center" });

  // Student info (right of photo)
  const infoX = photoX + 24;
  doc.setTextColor(20, 20, 20);
  doc.setFontSize(7);
  doc.setFont("helvetica", "bold");
  doc.text(student.name, infoX, photoY + 3);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(6);
