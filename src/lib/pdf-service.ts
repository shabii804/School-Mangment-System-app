  doc.setLineWidth(1);
  doc.roundedRect(cardX, cardY, cardW, cardH, 3, 3, "S");

  // Header band
  doc.setFillColor(21, 133, 122);
  doc.roundedRect(cardX, cardY, cardW, 14, 3, 3, "F");
