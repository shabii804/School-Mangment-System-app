  doc.setFontSize(8);
  doc.setFont("helvetica", "bold");
  doc.text(school.name, cardX + cardW / 2 + 2, cardY + 6, { align: "center" });
  doc.setFontSize(6);
  doc.setFont("helvetica", "normal");
  doc.text("STUDENT IDENTITY CARD", cardX + cardW / 2 + 2, cardY + 11, { align: "center" });

  // Photo placeholder (left)
  const photoX = cardX + 4;
  const photoY = cardY + 18;
